import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath, URL } from "node:url";
import { environmentCopy, environmentSources } from "../src/lib/environment.ts";
const escape = (value) =>
  String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
for (const locale of ["zh", "en"]) {
  const copy = environmentCopy[locale];
  const path = locale === "zh" ? "environment/" : "en/environment/";
  const directory = new URL(`../${path}`, import.meta.url);
  const sources = environmentSources
    .map(
      (source) =>
        `<li><a href="${escape(source.url)}" rel="noreferrer">${escape(source.title)}</a></li>`,
    )
    .join("\n");
  const facts = copy.facts
    .map((fact) => `<section><h2>${escape(fact[1])}</h2><p>${escape(fact[2])}</p></section>`)
    .join("\n");
  await mkdir(directory, { recursive: true });
  await writeFile(
    fileURLToPath(new URL("index.html", directory)),
    `<!doctype html>
<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- Generated by scripts/generate-environment-pages.mjs from src/lib/environment.ts. -->
<html lang="${locale === "zh" ? "zh-CN" : "en"}">
<head>
<meta charset="UTF-8" /><meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>${escape(copy.title)} | ImgConvert</title>
<meta name="description" content="${escape(copy.intro)}" />
<meta name="theme-color" content="#fcf9f3" />
<link rel="icon" type="image/png" href="/images/product/app-icon.png" />
<link rel="canonical" href="https://imgconvert.web.casa/${path}" />
<link rel="alternate" hreflang="zh-CN" href="https://imgconvert.web.casa/environment/" />
<link rel="alternate" hreflang="en" href="https://imgconvert.web.casa/en/environment/" />
<link rel="alternate" hreflang="x-default" href="https://imgconvert.web.casa/environment/" />
</head>
<body><div id="app"><main class="seo-fallback">
<h1>${escape(copy.title)}</h1><p>${escape(copy.intro)}</p>
${facts}
<section><h2>${escape(copy.individual)}</h2><p>${escape(copy.individualIntro)}</p></section>
<section><h2>${escape(copy.global)}</h2><p>${escape(copy.globalIntro)}</p></section>
<p>${escape(copy.noJs)}</p>
<section><h2>${escape(copy.method)}</h2><p>${escape(copy.formula)}</p><p>${escape(copy.factors)}</p><p>${escape(copy.limits)}</p></section>
<section><h2>${escape(copy.practical)}</h2><ul>${copy.actions.map((action) => `<li>${escape(action)}</li>`).join("")}</ul></section>
<section><h2>${escape(copy.sources)}</h2><ul>${sources}</ul></section>
<p>${escape(copy.privacy)}</p><a href="/convert/">${escape(copy.convert)}</a>
</main></div><script type="module" src="/src/main.ts"></script></body></html>\n`,
  );
}
