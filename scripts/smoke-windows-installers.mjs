import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, statSync } from "node:fs";
import { rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const isWindows = os.platform() === "win32";
let tmpRoot = null;

const options = {
  profile: "release",
  bundles: ["msi", "nsis"],
  allowNonWindows: false,
  keepInstalled: false,
};

for (const arg of process.argv.slice(2)) {
  if (arg === "--") {
    continue;
  } else if (arg.startsWith("--profile=")) {
    options.profile = arg.slice("--profile=".length);
  } else if (arg.startsWith("--bundles=")) {
    options.bundles = parseBundles(arg.slice("--bundles=".length));
  } else if (arg === "--allow-non-windows") {
    options.allowNonWindows = true;
  } else if (arg === "--keep-installed") {
    options.keepInstalled = true;
  } else if (arg === "--help" || arg === "-h") {
    printHelp();
    process.exit(0);
  } else {
    fail(`unknown argument: ${arg}`);
  }
}

if (!isWindows && !options.allowNonWindows) {
  fail(
    "Windows installer install smoke must run on Windows. Pass --allow-non-windows only for preflight.",
  );
}
if (!["debug", "release"].includes(options.profile)) {
  fail(`unsupported profile: ${options.profile}`);
}
for (const bundle of options.bundles) {
  if (!["msi", "nsis"].includes(bundle)) {
    fail(`unsupported Windows bundle: ${bundle}`);
  }
}

const artifacts = collectWindowsArtifacts(options.profile, options.bundles);
if (artifacts.length === 0) {
  fail("no Windows installers found for install smoke");
}

if (!isWindows) {
  for (const artifact of artifacts) {
    console.log(
      `preflight artifact ${path.relative(repoRoot, artifact)} (${statSync(artifact).size} bytes)`,
    );
  }
  process.exit(0);
}

tmpRoot = mkdtempSync(path.join(os.tmpdir(), "imgconvert-windows-install-smoke-"));

for (const artifact of artifacts) {
  if (artifact.toLowerCase().endsWith(".exe")) {
    smokeNsisInstaller(artifact);
  } else if (artifact.toLowerCase().endsWith(".msi")) {
    smokeMsiInstaller(artifact);
  }
}

if (!options.keepInstalled) {
  await removeTemporaryRoot(tmpRoot);
}

console.log(`Windows installer install smoke completed (${artifacts.length} artifact(s)).`);

async function removeTemporaryRoot(directory) {
  // NSIS can leave a short-lived handle behind after its uninstaller exits.
  // The promise API schedules retry delays for Windows EPERM/EBUSY cleanup.
  await rm(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
}

function smokeNsisInstaller(installer) {
  // Keep this intentionally non-ASCII and space-containing. NSIS receives the
  // install directory as a command-line argument, and the app then runs from
  // it, so this catches a common Windows packaging/path regression.
  const installDir = path.join(requiredTmpRoot(), "中文 路径", "ImgConvert");
  // NSIS requires /D= to be the final, unquoted argument even when the path
  // contains spaces. Node otherwise quotes that argument on Windows, causing
  // the installer to silently ignore the requested directory. The directory
  // is generated by this smoke test, never supplied by an untrusted caller.
  run(installer, ["/S", `/D=${installDir}`], `install NSIS ${path.basename(installer)}`, {
    windowsVerbatimArguments: true,
  });
  const executable = findInstalledExecutable([installDir]);
  verifyInstalledExecutableArchitecture(executable, "NSIS");
  verifyNsisRecordedInstallLocation(installDir);
  runInstalledSmoke(executable, "nsis");
  if (!options.keepInstalled) {
    const uninstaller = findUninstaller(installDir);
    if (!uninstaller) {
      fail(`NSIS uninstaller was not found under ${installDir}`);
    }
    run(uninstaller, ["/S"], "uninstall NSIS smoke package");
    assertNoInstalledExecutable([installDir], "NSIS uninstall");
  }
}

function smokeMsiInstaller(installer) {
  const roots = standardInstallRoots();
  assertNoInstalledExecutable(roots, "MSI install preflight");
  const log = path.join(requiredTmpRoot(), "msi-install.log");
  run(
    "msiexec.exe",
    ["/i", installer, "/qn", "/norestart", "/L*v", log],
    `install MSI ${path.basename(installer)}`,
  );
  const executable = findInstalledExecutable(roots);
  verifyInstalledExecutableArchitecture(executable, "MSI");
  runInstalledSmoke(executable, "msi");
  if (!options.keepInstalled) {
    run("msiexec.exe", ["/x", installer, "/qn", "/norestart"], "uninstall MSI smoke package");
    assertNoInstalledExecutable(roots, "MSI uninstall");
  }
}

function runInstalledSmoke(executable, label) {
  run(executable, [], `installed ${label} package conversion smoke`, {
    env: {
      IMGCONVERT_PACKAGE_CONVERT_SMOKE: "1",
      IMGCONVERT_PACKAGE_CONVERT_SMOKE_FORMATS: "jpeg,webp,png,avif",
      IMGCONVERT_PACKAGE_CONVERT_SMOKE_DIR: path.join(requiredTmpRoot(), `${label} 转换 输出`),
    },
  });
}

function findInstalledExecutable(roots) {
  const candidates = installedExecutables(roots).sort((a, b) => b.length - a.length);
  if (!candidates[0]) {
    fail(`installed ImgConvert.exe was not found under: ${roots.filter(Boolean).join(", ")}`);
  }
  return candidates[0];
}

function assertNoInstalledExecutable(roots, label) {
  const candidates = installedExecutables(roots);
  if (candidates.length > 0) {
    fail(
      `${label} found an existing ImgConvert.exe and refuses to overwrite or leave it behind: ${candidates.join(", ")}`,
    );
  }
}

function installedExecutables(roots) {
  return roots
    .filter(Boolean)
    .flatMap((root) => collectFiles(root))
    .filter((file) => path.basename(file).toLowerCase() === "imgconvert.exe");
}

function verifyInstalledExecutableArchitecture(executable, label) {
  const expected = expectedWindowsArchitecture();
  const actual = peProcessorArchitecture(executable);
  if (actual !== expected) {
    fail(`${label} installed ImgConvert.exe has architecture ${actual}, expected ${expected}`);
  }
  console.log(`verified ${label} installed ImgConvert.exe architecture: ${actual}`);
}

function verifyNsisRecordedInstallLocation(installDir) {
  const registryKey = "Registry::HKEY_CURRENT_USER\\Software\\ImgConvert contributors\\ImgConvert";
  const command = [
    "$ErrorActionPreference = 'Stop'",
    `$value = (Get-Item -LiteralPath '${registryKey}').GetValue('')`,
    "if ([string]::IsNullOrWhiteSpace($value)) { throw 'missing default registry value' }",
    "[Console]::Write($value)",
  ].join("; ");
  const result = spawnSync(
    "pwsh.exe",
    ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command],
    { cwd: repoRoot, encoding: "utf8", windowsHide: true },
  );
  if (result.error || result.status !== 0) {
    fail("NSIS install did not record its current-user install location");
  }
  const recorded = String(result.stdout ?? "").trim();
  if (normalizeWindowsPath(recorded) !== normalizeWindowsPath(installDir)) {
    fail(`NSIS recorded install location differs from custom path: ${recorded}`);
  }
  console.log("verified NSIS current-user install location registry entry.");
}

function normalizeWindowsPath(value) {
  return path.win32
    .normalize(String(value))
    .replace(/[\\/]+$/, "")
    .toLowerCase();
}

function peProcessorArchitecture(file) {
  const binary = readFileSync(file);
  if (binary.length < 0x40 || binary.readUInt16LE(0) !== 0x5a4d) {
    fail(`${file} is not a valid PE executable (missing MZ header)`);
  }
  const peOffset = binary.readUInt32LE(0x3c);
  if (peOffset > binary.length - 6 || binary.readUInt32LE(peOffset) !== 0x00004550) {
    fail(`${file} is not a valid PE executable (missing PE header)`);
  }
  const machine = binary.readUInt16LE(peOffset + 4);
  if (machine === 0x8664) return "x64";
  if (machine === 0xaa64) return "arm64";
  fail(`${file} uses unsupported PE machine type 0x${machine.toString(16).padStart(4, "0")}`);
}

function expectedWindowsArchitecture() {
  const configured = String(process.env.WINDOWS_STORE_PROCESSOR_ARCHITECTURE ?? "")
    .trim()
    .toLowerCase();
  if (configured) {
    if (["x64", "arm64"].includes(configured)) {
      return configured;
    }
    fail(`unsupported WINDOWS_STORE_PROCESSOR_ARCHITECTURE: ${configured}`);
  }
  if (process.arch === "arm64") return "arm64";
  if (process.arch === "x64") return "x64";
  fail(`unsupported Windows Node architecture: ${process.arch}`);
}

function findUninstaller(root) {
  return collectFiles(root).find((file) => path.basename(file).toLowerCase().includes("uninstall"));
}

function standardInstallRoots() {
  return [
    process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, "Programs", "ImgConvert"),
    process.env.ProgramFiles && path.join(process.env.ProgramFiles, "ImgConvert"),
    process.env["ProgramFiles(x86)"] && path.join(process.env["ProgramFiles(x86)"], "ImgConvert"),
  ].filter(Boolean);
}

function collectWindowsArtifacts(profile, bundles) {
  const expectedExtensions = {
    msi: ".msi",
    nsis: ".exe",
  };
  const bundleRoot = path.join(cargoTargetRoot(), profile, "bundle");
  const artifacts = [];
  for (const bundle of bundles) {
    const bundleDir = path.join(bundleRoot, bundle);
    artifacts.push(
      ...collectFiles(bundleDir).filter((file) =>
        file.toLowerCase().endsWith(expectedExtensions[bundle]),
      ),
    );
  }
  return artifacts.sort();
}

function collectFiles(dir) {
  try {
    const files = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const entryPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        files.push(...collectFiles(entryPath));
      } else if (entry.isFile()) {
        files.push(entryPath);
      }
    }
    return files;
  } catch {
    return [];
  }
}

function parseBundles(value) {
  return value
    .split(",")
    .map((bundle) => bundle.trim().toLowerCase())
    .filter(Boolean);
}

function run(command, args, label, options = {}) {
  console.log(`\n> ${label}`);
  const result = spawnSync(command, args, {
    cwd: repoRoot,
    env: { ...process.env, ...(options.env ?? {}) },
    stdio: "inherit",
    windowsVerbatimArguments: options.windowsVerbatimArguments === true,
  });
  if (result.error) {
    if (options.allowFailure) {
      console.warn(`${label} failed to start: ${result.error.message}`);
      return;
    }
    fail(`${label} failed to start: ${result.error.message}`);
  }
  if (result.status !== 0) {
    if (options.allowFailure) {
      console.warn(`${label} failed with exit code ${result.status ?? 1}`);
      return;
    }
    fail(`${label} failed with exit code ${result.status ?? 1}`);
  }
}

function requiredTmpRoot() {
  if (!tmpRoot) {
    fail("temporary install smoke directory was not initialized");
  }
  return tmpRoot;
}

function cargoTargetRoot() {
  return process.env.CARGO_TARGET_DIR
    ? path.resolve(process.env.CARGO_TARGET_DIR)
    : path.join(repoRoot, "src-tauri", "target");
}

function printHelp() {
  console.log(`Usage: node scripts/smoke-windows-installers.mjs [options]

Options:
  --profile=<profile>     release or debug, defaults to release.
  --bundles=<list>        Comma-separated bundles, defaults to msi,nsis.
  --allow-non-windows     Allow non-Windows artifact preflight.
  --keep-installed        Leave installed packages and temp directory in place.
`);
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
